import { build } from "esbuild";
import { gunzipSync, gzipSync } from "node:zlib";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { CANONICAL_SCHEMA_VERSION } from "../dashboard/site/src/data/model/schema.js";

const { outputFiles } = await build({
  entryPoints: [fileURLToPath(new URL("../dashboard/report/hydrate-local-logs.mjs", import.meta.url))],
  bundle: true,
  format: "iife",
  globalName: "CaoIngest",
  target: "es2017",
  minify: true,
  write: false,
});
const artifact = new URL("../internal/dashboardingest/normalize.generated.js.gz", import.meta.url);
const schemaArtifact = new URL("../internal/dashboardingest/schema.generated.go", import.meta.url);
const schema = `// Code generated by scripts/generate-dashboard-ingest.mjs; DO NOT EDIT.

package dashboardingest

const SchemaVersion = ${CANONICAL_SCHEMA_VERSION}
`;
const generated = gzipSync(outputFiles[0].contents);
if (process.argv.includes("--check")) {
  if (!Buffer.from(outputFiles[0].contents).equals(gunzipSync(await readFile(artifact)))) {
    throw new Error("Embedded log normalizer is stale; run npm run generate:dashboard-ingest.");
  }
  if ((await readFile(schemaArtifact, "utf8")).replace(/\r\n/g, "\n") !== schema) {
    throw new Error("Embedded canonical schema version is stale; run npm run generate:dashboard-ingest.");
  }
} else {
  await writeFile(artifact, generated);
  await writeFile(schemaArtifact, schema);
}
