test("fresh discovery cannot rewrite or discard previously accepted native delivery facts", () => {
  const previous = { metric: { id: "fixed", version: "v1" },
    events: [{ id: "PR_1", at: createdAt, value: 1, acceptance: { ref: sha("a") } }] };
  verifyPreservedDeliveries(previous, structuredClone(previous));
  for (const change of [
    next => { next.events = []; },
    next => { next.events[0].value = 2; },
    next => { next.events[0].at = until; },
    next => { next.events[0].acceptance.ref = sha("b"); },
    next => { next.metric.version = "v2"; },
  ]) {
    const next = structuredClone(previous);
    change(next);
    assert.throws(() => verifyPreservedDeliveries(previous, next), /changed/);
  }
});

test("copied tracking/run references do not turn another object's applied receipt into creation proof", () => {
  const issue = { id: "I_1", number: 1 };
  const row = number => ({ type: "create_issue", number, repo: repository,
    url: `https://github.com/${repository}/issues/${number}`, metadata: { node_id: `I_${number}` } });
  const wrong = appliedReceipt(JSON.stringify(row(2)), issue);
  assert.equal(wrong.status, "not-applied-to-output");
  assert.match(wrong.reason, /does not record creation/);
  const text = [row(2), row(1)].map(item => JSON.stringify(item)).join("\n");
  const matching = appliedReceipt(text, issue);
  assert.equal(matching.status, "available");
  assert.equal(matching.sourceRowIndex, 1);
  assert.equal(matching.sourceEntrySha256, bytesDigest(text));
  assert.equal(JSON.parse(matching.content).number, 1);
  assert.equal(appliedReceipt([row(1), row(1)].map(item => JSON.stringify(item)).join("\n"), issue).status, "not-applied-to-output");
  assert.throws(() => appliedReceipt(JSON.stringify({ ...row(1), metadata: { node_id: "other" } }), issue), /identity mismatch/);
});

function fakeHistory() {
  const body = `${modern()}\nRefactor pkg/a.go.`;
  return (endpoint, query) => {
    if (endpoint === `repos/${repository}` || endpoint === "repos/githubnext/gh-aw") return { id: 1, full_name: repository };
    if (endpoint.startsWith(`repos/${repository}/commits?path=`)) {
      return [{ sha: sha("a"), commit: { committer: { date: createdAt } } }];
    }
    if (endpoint === `repos/${repository}/commits/${sha("a")}`) return {
      parents: [{ sha: sha("0") }], files: [sourcePath, sourcePath.replace(".md", ".lock.yml")]
        .map(filename => ({ filename, status: "added" })),
    };
    if (endpoint.startsWith("search/issues?")) return { total_count: 1, incomplete_results: false,
      items: [{ number: 1, node_id: "I_1", title: "[file-diet] pkg/a.go", body, created_at: createdAt }] };
    if (query) return { data: { repository: { n1: graph() } } };
    if (endpoint.endsWith("/actions/runs/42")) return {
      id: 42, repository: { full_name: repository }, path: sourcePath.replace(".md", ".lock.yml"), head_sha: sha("a"), run_attempt: 1,
    };
    if (endpoint.includes("/artifacts?")) return { total_count: 0, artifacts: [] };
    if (endpoint.includes("/timeline?")) return [];
    if (endpoint.startsWith(`repos/${repository}/commits?until=`)) return [
      { sha: sha("b"), commit: { committer: { date: createdAt } } },
    ];
    throw new Error(`Unexpected request: ${endpoint}`);
  };
}

test("bounded fresh history keeps tracked outputs, native snapshots and explicit source coverage", () => {
  const proof = acquireFileDietHistory(fakeHistory(), until);
  assert.equal(proof.until, until);
  assert.ok(Date.parse(proof.observedAt) >= Date.parse(until));
  assert.equal(proof.issues.length, 1);
  assert.equal(proof.issues[0].reference.trackerId, "stable-output-series");
  assert.equal(proof.issues[0].run.validation.headSha, sha("a"));
  assert.equal(proof.snapshots.at(-1).at, until);
  assert.ok(proof.discovery.every(item => item.complete));
  for (const bad of [
    { total_count: 1000, incomplete_results: false, items: [] },
    { total_count: 1, incomplete_results: true, items: [] },
    { total_count: 2, incomplete_results: false, items: [] },
  ]) assert.throws(() => acquireFileDietHistory((endpoint, query) =>
    endpoint.startsWith("search/issues?") ? bad : fakeHistory()(endpoint, query), until), /coverage|truncated/);
});

test("incremental history starts discovery at the retained cutoff and reuses immutable identities", () => {
  const initial = acquireFileDietHistory(fakeHistory(), "2026-10-18T11:54:09Z");
  const next = "2026-10-31T02:00:00Z";
  const calls = [];
  const source = fakeHistory();
  const proof = acquireFileDietHistory((endpoint, query) => {
    calls.push(endpoint);
    return source(endpoint, query);
  }, next, initial);
  assert.deepEqual(proof.adoption, initial.adoption);
  assert.equal(proof.issues.length, initial.issues.length);
  assert.equal(proof.issues[0].reference.runId, initial.issues[0].reference.runId);
  assert.ok(calls.some(endpoint => endpoint.includes(`since=${initial.until}`)));
  assert.ok(calls.filter(endpoint => endpoint.startsWith("search/issues?"))
    .every(endpoint => decodeURIComponent(endpoint).includes(`updated:${initial.until.slice(0, 10)}..${next.slice(0, 10)}`)));
  assert.ok(!calls.includes(`repos/${repository}/commits/${sha("a")}`));
  assert.ok(!calls.some(endpoint => endpoint.endsWith("/actions/runs/42")));
  assert.ok(!calls.some(endpoint => endpoint.includes("/artifacts?")));
  assert.deepEqual(proof.snapshots.map(snapshot => snapshot.at), [
    ...Array.from({ length: 13 }, (_, index) =>
      `2026-10-${String(index + 19).padStart(2, "0")}T00:00:00Z`),
    next,
  ]);
  assert.equal(calls.filter(endpoint => endpoint.startsWith(`repos/${repository}/commits?until=`)).length, 14);
});

test("Git evidence reuses immutable facts and resolves new deliveries from actual parent headers", t => {
  const directory = temporary(t);
  const content = Buffer.from("package example\n");
  const blob = createHash("sha1").update(`blob ${content.length}\0`).update(content).digest("hex");
  const proof = { repository, until, adoption: { baselineCommit: sha("0"), commit: sha("a") },
    snapshots: [{ commit: sha("a") }], issues: [], history: [],
    pulls: [{ id: "PR_2", mergeSha: sha("b"), headSha: sha("c"), mergedAt: "2026-02-01T00:00:00Z" }] };
  const calls = [];
  const execute = (command, args) => {
    assert.equal(command, "git");
    const actual = args.slice(2);
    calls.push(actual);
    if (actual[0] === "ls-tree") return `100644 blob ${blob}\tpkg/a.go\0`;
    if (actual[0] === "cat-file" && actual[1] === "-p") return `tree ${sha("f")}\nparent ${sha("d")}\n\nmerge`;
    if (actual[0] === "cat-file" && actual[1] === "--batch") {
      return Buffer.concat([Buffer.from(`${blob} blob ${content.length}\n`), content, Buffer.from("\n")]);
    }
    return "";
  };
  const result = collectGitInventories(proof, null, directory, file => file.endsWith(".go"), execute);
  assert.equal(proof.pulls[0].preMergeSha, sha("d"));
  assert.equal(result.newBlobs, 1);
  assert.equal(result.uniqueBlobs, 1);
  assert.equal(result.inventories.get(sha("b")).files[0].lines, 1);
  assert.ok(calls.some(args => args.includes(sha("d"))), "The actual merge parent must be fetched.");
  const prior = { proof, inventories: new Map([...result.inventories].map(([commit, item]) => [commit, item.files])) };
  const reused = collectGitInventories(proof, prior, directory, file => file.endsWith(".go"), execute);
  assert.equal(reused.newInventories, 0);
  assert.equal(reused.newBlobs, 0);
});

test("fresh collection refuses future cutoffs and existing output, and cleans temporary work on failure", t => {
  const directory = temporary(t);
  assert.throws(() => refreshFileDiet({ endAt: "2999-01-01T00:00:00Z", output: directory }), /endpoint/);
  assert.throws(() => refreshFileDiet({ endAt: until, output: directory }), /existing/);
  const before = readdirSync(root).filter(file => file.startsWith(".file-diet-acquire-"));
  assert.throws(() => refreshFileDiet({ endAt: until, previous: path.join(directory, "absent"), output: path.join(directory, "result") }), /ENOENT/);
  assert.deepEqual(readdirSync(root).filter(file => file.startsWith(".file-diet-acquire-")), before);
  assert.ok(!existsSync(path.join(directory, "result")));
  const result = execFileSync(process.execPath, ["--check",
    path.join(root, ".github/skills/add-operational-value/examples/acquire-file-diet.mjs")]);
  assert.equal(result.length, 0);
});
