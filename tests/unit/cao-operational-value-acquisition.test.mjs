function temporary(t) {
  mkdirSync(path.join(root, ".tmp"), { recursive: true });
  const directory = mkdtempSync(path.join(root, ".tmp", "value-acquisition-test-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  return directory;
}

test("tracking IDs, execution markers and named legacy footers discover identities without claiming receipts", () => {
  const reference = workflowReference(modern(), identity);
  assert.equal(reference.runId, "42");
  assert.equal(reference.trackerId, "stable-output-series");
  assert.equal(reference.marker, "gh-aw-execution-v1");
  assert.equal(workflowReference("<!-- gh-aw-tracker-id: daily-file-diet -->", identity).runId, null);
  assert.equal(workflowReference("<!-- gh-aw-tracker-id: stable-output-series -->",
    { ...identity, trackerIds: ["stable-output-series"] }).trackerId, "stable-output-series");
  assert.equal(workflowReference("<!-- gh-aw-tracker-id: stable-output-series -->", identity), null);
  assert.equal(workflowReference("<!-- gh-aw-workflow-id: daily-file-diet -->", identity).marker, "tracking-only");
  assert.equal(workflowReference("AI generated by [Daily File Diet](https://github.com/githubnext/gh-aw/actions/runs/42)", identity).runId, "42");
  assert.equal(workflowReference("<!-- gh-aw-agentic-workflow: Daily File Diet, workflow_id: daily-file-diet, id: 42, run: https://github.com/github/gh-aw/actions/runs/42 -->", identity).runId, "42");
  assert.equal(workflowReference("[file-diet] an ordinary unrelated issue", identity), null);
  assert.equal(workflowReference(modern().replace("workflow-id: daily-file-diet", "workflow-id: another"), identity), null);
  assert.throws(() => workflowReference(`${modern()}\n<!-- gh-aw-workflow-id: another -->`, identity), /Conflicting tracking/);
  assert.throws(() => workflowReference(`${modern()}\nAI generated by [Daily File Diet](https://github.com/github/gh-aw/actions/runs/43)`, identity), /Conflicting producer/);
  assert.throws(() => workflowReference(modern().replaceAll("github/gh-aw", "another/repo"), identity), /outside declared/);
  const run = { id: 42, repository: { full_name: repository }, path: sourcePath.replace(".md", ".lock.yml"),
    head_sha: sha("a"), run_attempt: 1 };
  assert.equal(validateProducer(reference, run, sourcePath, repository, identity.aliases).headSha, sha("a"));
  assert.throws(() => validateProducer(reference, { ...run, path: ".github/workflows/another.lock.yml" },
    sourcePath, repository, identity.aliases), /does not match/);
});

function graph(number = 1, pull = false) {
  return { __typename: pull ? "PullRequest" : "Issue", id: `${pull ? "PR" : "I"}_${number}`, number,
    url: `https://github.com/${repository}/${pull ? "pull" : "issues"}/${number}`,
    repository: { nameWithOwner: repository }, state: pull ? "MERGED" : "CLOSED",
    createdAt, updatedAt: createdAt, closedAt: "2026-02-01T00:00:01Z",
    ...(pull ? { mergedAt: "2026-02-01T00:00:00Z", mergeCommit: { oid: sha("b") },
      closingIssuesReferences: { nodes: [graph(1)], pageInfo: { hasNextPage: false } } } : {}),
    timelineItems: { nodes: [], pageInfo: { hasNextPage: false } } };
}

test("dated closer identity survives without a connected event; truncation stays explicit", () => {
  const value = graph();
  value.timelineItems.nodes = [
    { __typename: "CrossReferencedEvent", createdAt: "2026-01-02T00:00:00Z", source: graph(2, true) },
    { __typename: "ClosedEvent", createdAt: "2026-02-01T00:00:01Z", closer: graph(2, true) },
  ];
  const normalized = normalizeGraph(value, until, repository);
  assert.deepEqual(normalized.edges.map(edge => [edge.relation, edge.at, edge.target.id]), [
    ["referenced-by", "2026-01-02T00:00:00Z", "PR_2"], ["closed-by", "2026-02-01T00:00:01Z", "PR_2"],
  ]);
  value.timelineItems.pageInfo.hasNextPage = true;
  assert.equal(normalizeGraph(value, until, repository).historyComplete, false);
  assert.throws(() => normalizeGraph(value, until, "another/repo"), /Incomplete/);
  assert.throws(() => graphQuery(repository, Array(11).fill(1)), /bounded/);
  const timeline = readTimeline(() => [{ event: "cross-referenced", created_at: createdAt,
    source: { issue: { number: 2, title: "Implementation", pull_request: {},
      repository_url: `https://api.github.com/repos/${repository}` } } }], repository, 1, until);
  assert.equal(timeline.events[0].target.number, 2);
  assert.equal(timeline.complete, true);
  const fullPage = Array(100).fill({ event: "labeled" });
  assert.equal(readTimeline(() => fullPage, repository, 1, until).complete, false);
});

test("fresh reader caches one acquisition, distinguishes deleted runs and surfaces access failures", t => {
  const directory = temporary(t);
  let calls = 0;
  const read = githubReader(directory, () => { calls++; return '{"id":1}'; });
  assert.deepEqual(read("repos/github/gh-aw"), { id: 1 });
  assert.deepEqual(read("repos/github/gh-aw"), { id: 1 });
  assert.equal(calls, 1);
  const failure = code => Object.assign(new Error(`HTTP ${code}`), { stderr: `(HTTP ${code})` });
  const missing = githubReader(path.join(directory, "missing"), () => { throw failure(404); });
  assert.equal(missing("repos/github/gh-aw/actions/runs/42").unavailable.status, 404);
  const forbidden = githubReader(path.join(directory, "forbidden"), () => { throw failure(403); });
  assert.throws(() => forbidden("repos/github/gh-aw/actions/runs/42"), /HTTP 403/);
  const invalid = githubReader(path.join(directory, "invalid"), () => '{"errors":[{"message":"denied"}]}');
  assert.throws(() => invalid("graphql", "query {}"), /Incomplete GitHub/);
});

test("expired source artifacts do not erase preserved applied-output receipt identity", () => {
  const content = '{"type":"create_issue","number":1}';
  const prior = { id: "I_1", number: 1, reference: { runId: "42" }, run: { validation: { headSha: sha("a") } },
    receipt: { status: "available", runId: 42, content, headSha: sha("a"),
      entrySha256: bytesDigest(content), archiveSha256: "b".repeat(64), digest: `sha256:${"b".repeat(64)}` } };
  const issue = { id: "I_1", number: 1, reference: { runId: "42" }, run: { validation: null } };
  assert.equal(preserveReceipt(issue, prior), true);
  assert.equal(issue.receipt.reusedFromPreservedProof, true);
  assert.equal(issue.run.validation.headSha, sha("a"));
  assert.throws(() => preserveReceipt({ ...issue, id: "another" }, prior), /identity changed/);
  assert.throws(() => preserveReceipt(issue, { ...prior, receipt: { ...prior.receipt, content: "changed" } }), /digest changed/);
});

