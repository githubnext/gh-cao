function fakeHistory() {
  const body = `${modern()}\nRefactor pkg/a.go.`;
  return (endpoint, query) => {
    if (endpoint === `repos/${repository}` || endpoint === "repos/githubnext/gh-aw") return { id: 1, full_name: repository };
    if (endpoint.startsWith(`repos/${repository}/commits?path=`)) {
      return [{ sha: sha("a"), commit: { committer: { date: createdAt } } }];
    }
    if (endpoint === `repos/${repository}/commits/${sha("a")}`) return {
      parents: [{ sha: sha("0") }], files: [sourcePath, sourcePath.replace(".md", ".lock.yml")]
        .map(filename => ({ filename, status: "added" })),
    };
    if (endpoint.startsWith("search/issues?")) return { total_count: 1, incomplete_results: false,
      items: [{ number: 1, node_id: "I_1", title: "[file-diet] pkg/a.go", body, created_at: createdAt }] };
    if (query) return { data: { repository: { n1: graph() } } };
    if (endpoint.endsWith("/actions/runs/42")) return {
      id: 42, repository: { full_name: repository }, path: sourcePath.replace(".md", ".lock.yml"), head_sha: sha("a"), run_attempt: 1,
    };
    if (endpoint.includes("/artifacts?")) return { total_count: 0, artifacts: [] };
    if (endpoint.includes("/timeline?")) return [];
    if (endpoint.startsWith(`repos/${repository}/commits?until=`)) return [
      { sha: sha("b"), commit: { committer: { date: createdAt } } },
    ];
    throw new Error(`Unexpected request: ${endpoint}`);
  };
}

