// Command generate-assets snapshots the authoritative Azure sources for offline native CLI use.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	directory := filepath.Join("..", "..", "server", "azure")
	names, err := filepath.Glob(filepath.Join(directory, "*.bicep"))
	if err != nil {
		return err
	}
	if len(names) == 0 {
		return fmt.Errorf("no canonical Azure Bicep sources found")
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by go generate ./internal/topology; DO NOT EDIT.\n\npackage topology\n\nconst (\n")
	var files bytes.Buffer
	files.WriteString("func baselineBicepFiles() map[string][]byte {\nreturn map[string][]byte{\n")
	for _, name := range names {
		content, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		base := filepath.Base(name)
		identifier := "azure"
		for _, part := range strings.Split(strings.TrimSuffix(base, ".bicep"), "-") {
			identifier += strings.ToUpper(part[:1]) + part[1:]
		}
		identifier += "Bicep"
		fmt.Fprintf(&source, "%s = `%s`\n", identifier, strings.ReplaceAll(string(content), "`", "` + \"`\" + `"))
		fmt.Fprintf(&files, "%q: []byte(%s),\n", base, identifier)
	}
	source.WriteString(")\n\n")
	files.WriteString("}\n}\n")
	source.Write(files.Bytes())
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format reconstructed Azure Bicep sources: %w", err)
	}
	if err := os.WriteFile("bicep_baseline.generated.go", formatted, 0o644); err != nil {
		return err
	}
	names = []string{filepath.Join(directory, "main.json")}
	destination := filepath.Join("assets", "azure-baseline.generated")
	if err := os.MkdirAll(destination, 0o755); err != nil {
		return err
	}
	generated := map[string]bool{}
	for _, name := range names {
		content, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		base := filepath.Base(name)
		if err := os.WriteFile(filepath.Join(destination, base), content, 0o644); err != nil {
			return err
		}
		generated[base] = true
	}
	entries, err := os.ReadDir(destination)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if !generated[entry.Name()] {
			if entry.IsDir() {
				return fmt.Errorf("unexpected directory in generated baseline: %s", entry.Name())
			}
			if err := os.Remove(filepath.Join(destination, entry.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}
