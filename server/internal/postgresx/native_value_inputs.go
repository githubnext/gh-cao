package postgresx

import (
	"context"
	"errors"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/githubnext/gh-cao/server/internal/model"
)

const nativeValueInputBytes = 16 << 20

// NativeValueInputs is a disposable, bounded copy of canonical preparation
// inputs, not an Activity lake or an execution-authority record.
type NativeValueInputs struct {
	Revision    int64
	Inventory   map[string]model.Source
	Collections []model.Row
}

func (s *Store) ReadNativeValueInputs(ctx context.Context, repositories []string) (NativeValueInputs, error) {
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	result := NativeValueInputs{Inventory: map[string]model.Source{}}
	if len(repositories) == 0 || len(repositories) > 10000 {
		return result, ErrValueInvalid
	}
	connection, err := pgx.ConnectConfig(ctx, s.config.Copy())
	if err != nil {
		return result, err
	}
	defer func() { _ = connection.Close(context.WithoutCancel(ctx)) }()
	tx, err := connection.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		return result, err
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(ctx)) }()
	if err := tx.QueryRow(ctx, `SELECT revision FROM cao_state WHERE namespace=$1`, s.namespace).Scan(&result.Revision); err != nil {
		return result, err
	}
	remaining := nativeValueInputBytes
	read := func(statement string) ([]model.Row, error) {
		rows, err := tx.Query(ctx, statement, s.namespace, repositories)
		if err != nil {
			return nil, err
		}
		defer rows.Close()
		result := []model.Row{}
		for rows.Next() {
			var content []byte
			if err := rows.Scan(&content); err != nil {
				return nil, err
			}
			remaining -= len(content)
			if remaining < 0 || len(result) >= 10000 {
				return nil, errors.New("native Value preparation exceeds its input budget")
			}
			var row model.Row
			if err := decodeValueJSON(content, &row); err != nil {
				return nil, err
			}
			result = append(result, row)
		}
		return result, rows.Err()
	}
	// Reconstruct only the published inventory transport fields required by the
	// existing reviewed health program. Stable identities are generated by its
	// production inventory adapter, not inferred from arbitrary inventory scope.
	repositoryRows, err := read(`SELECT jsonb_build_object('organization',owner,'repository',name)
		FROM repositories WHERE namespace=$1 AND lower(owner || '/' || name)=ANY($2::text[])
		ORDER BY id LIMIT 10001`)
	if err != nil {
		return result, err
	}
	workflowRows, err := read(`SELECT jsonb_build_object('organization',r.owner,'repository',r.name,'workflow',w.path)
		FROM workflows w JOIN repositories r ON r.namespace=w.namespace AND r.id=w.repository_id
		WHERE w.namespace=$1 AND lower(r.owner || '/' || r.name)=ANY($2::text[])
		ORDER BY w.id LIMIT 10001`)
	if err != nil {
		return result, err
	}
	var observed string
	if err := tx.QueryRow(ctx, `SELECT to_char(evaluated_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
		FROM cao_state WHERE namespace=$1`, s.namespace).Scan(&observed); err != nil {
		return result, err
	}
	for name, rows := range map[string][]model.Row{"repositories": repositoryRows, "workflows": workflowRows} {
		metadata := model.Metadata{"availability": "unavailable", "completeness": "unknown", "freshness": "unknown"}
		var availability, completeness, freshness string
		var asOf, retrieved *time.Time
		err := tx.QueryRow(ctx, `SELECT availability,completeness,freshness,as_of,retrieved_at
			FROM cao_quality WHERE namespace=$1 AND collection=$2`, s.namespace, "$"+name).
			Scan(&availability, &completeness, &freshness, &asOf, &retrieved)
		if err != nil && !errors.Is(err, pgx.ErrNoRows) {
			return result, err
		}
		if err == nil {
			metadata["availability"], metadata["completeness"], metadata["freshness"] = availability, completeness, freshness
			metadata["as-of"] = observed
			if asOf != nil {
				metadata["as-of"] = asOf.UTC().Format(time.RFC3339Nano)
			}
			if retrieved != nil {
				metadata["retrieved-at"] = retrieved.UTC().Format(time.RFC3339Nano)
			}
		}
		result.Inventory[name] = model.Source{Source: name, Rows: rows, Metadata: metadata}
	}
	result.Collections, err = read(`SELECT ` + valueJSONProjection("$workflowValueCollections") + `
		FROM workflow_value_collections t WHERE namespace=$1 AND lower(repository)=ANY($2::text[])
		ORDER BY id LIMIT 10001`)
	if err != nil {
		return result, err
	}
	if err := tx.Commit(ctx); err != nil {
		return result, err
	}
	return result, nil
}
