const fileDietSourcePath = ".github/workflows/daily-file-diet.md"

var errFileDietReferenceNotFound = errors.New("file Diet tracking reference not found")

var (
	fileDietCommentPattern = regexp.MustCompile(`(?s)<!--(.*?)-->`)
	fileDietPathPattern    = regexp.MustCompile(`pkg/[\w./-]+\.go\b`)
	fileDietFooterPattern  = regexp.MustCompile(`AI generated by \[Daily File Diet\]\(https://github\.com/([\w.-]+/[\w.-]+)/actions/runs/(\d+)\)`)
	fileDietRunURLPattern  = regexp.MustCompile(`^https://github\.com/([\w.-]+/[\w.-]+)/actions/runs/(\d+)(?:/attempts/(\d+))?$`)
	fileDietLegacyRun      = regexp.MustCompile(`^https://github\.com/([\w.-]+/[\w.-]+)/actions/runs/(\d+)$`)
	fileDietSourceName     = regexp.MustCompile(`(?i)^\[file-diet\]`)
	fileDietRefactor       = regexp.MustCompile(`(?i)\brefactor\b`)
)

type fileDietRead func(context.Context, string, string, bool) ([]byte, error)

func fileDietReadJSON[T any](ctx context.Context, read fileDietRead, endpoint, query string) (T, error) {
	var value T
	content, err := read(ctx, endpoint, query, false)
	if err != nil {
		return value, err
	}
	if err := json.Unmarshal(content, &value); err != nil {
		return value, errors.New("incomplete reviewed File Diet GitHub response")
	}
	return value, nil
}

func fileDietInstant(text string) bool {
	return !fileDietTime(text).IsZero()
}

func fileDietReferenceFor(body string) (*fileDietReference, error) {
	var workflowID, trackerID string
	var candidates []fileDietReference
	for _, match := range fileDietCommentPattern.FindAllStringSubmatch(body, -1) {
		comment := strings.TrimSpace(match[1])
		for _, marker := range []struct {
			prefix string
			target *string
		}{{"gh-aw-workflow-id:", &workflowID}, {"gh-aw-tracker-id:", &trackerID}} {
			if strings.HasPrefix(comment, marker.prefix) {
				value := strings.TrimSpace(strings.TrimPrefix(comment, marker.prefix))
				if value == "" || strings.ContainsAny(value, " \t\r\n") ||
					*marker.target != "" && *marker.target != value {
					return nil, errors.New("conflicting File Diet tracking identities")
				}
				*marker.target = value
			}
		}
		if strings.HasPrefix(comment, "gh-aw-execution:") {
			var marker struct {
				Version      int    `json:"version"`
				Repository   string `json:"repository"`
				RunID        int64  `json:"run_id"`
				RunAttempt   int    `json:"run_attempt"`
				AWWorkflowID string `json:"aw_workflow_id"`
				RunURL       string `json:"run_url"`
			}
			if err := json.Unmarshal([]byte(strings.TrimSpace(strings.TrimPrefix(comment, "gh-aw-execution:"))), &marker); err != nil ||
				marker.Version != 1 || marker.RunURL == "" {
				return nil, errors.New("invalid File Diet execution marker")
			}
			if marker.AWWorkflowID != dailyFileDietWorkflow {
				continue
			}
			urlParts := fileDietRunURLPattern.FindStringSubmatch(marker.RunURL)
			if len(urlParts) != 4 || !strings.EqualFold(marker.Repository, urlParts[1]) ||
				strconv.FormatInt(marker.RunID, 10) != urlParts[2] || marker.RunAttempt < 1 ||
				urlParts[3] != "" && urlParts[3] != strconv.Itoa(marker.RunAttempt) {
				return nil, errors.New("conflicting File Diet execution identity")
			}
			candidates = append(candidates, fileDietReference{
				Repository: urlParts[1], RunID: &urlParts[2], Attempt: &marker.RunAttempt, Marker: "gh-aw-execution-v1",
			})
		}
		if strings.HasPrefix(comment, "gh-aw-agentic-workflow:") &&
			strings.HasPrefix(strings.TrimSpace(strings.TrimPrefix(comment, "gh-aw-agentic-workflow:")), "Daily File Diet") {
			runField := strings.SplitN(comment, "run:", 2)
			if len(runField) != 2 {
				return nil, errors.New("legacy File Diet marker lacks a run reference")
			}
			matches := fileDietLegacyRun.FindStringSubmatch(strings.TrimSpace(runField[1]))
			if len(matches) != 3 {
				return nil, errors.New("legacy File Diet marker lacks a run reference")
			}
			for _, field := range []struct {
				name      string
				delimiter string
			}{{"workflow_id: ", "workflow_id: "}, {"id: ", ", id: "}} {
				if marker := strings.SplitN(comment, field.delimiter, 2); len(marker) == 2 {
					selected := strings.FieldsFunc(marker[1], func(r rune) bool { return r == ',' || r == ' ' || r == '\n' })
					if len(selected) == 0 || field.name == "workflow_id: " && selected[0] != dailyFileDietWorkflow ||
						field.name == "id: " && selected[0] != matches[2] {
						return nil, errors.New("conflicting legacy File Diet identity")
					}
				}
			}
			candidates = append(candidates, fileDietReference{Repository: matches[1], RunID: &matches[2], Marker: "gh-aw-agentic-workflow"})
		}
	}
	for _, match := range fileDietFooterPattern.FindAllStringSubmatch(body, -1) {
		candidates = append(candidates, fileDietReference{Repository: match[1], RunID: &match[2], Marker: "named-run-footer"})
	}
	var selected *fileDietReference
	runID := ""
	attempt := 0
	for index := range candidates {
		candidate := &candidates[index]
		if !strings.EqualFold(candidate.Repository, dailyFileDietRepository) &&
			!strings.EqualFold(candidate.Repository, "githubnext/gh-aw") {
			return nil, errors.New("file Diet producer outside reviewed repository")
		}
		if runID != "" && runID != *candidate.RunID ||
			attempt != 0 && candidate.Attempt != nil && attempt != *candidate.Attempt {
			return nil, errors.New("conflicting File Diet producer runs or attempts")
		}
		runID = *candidate.RunID
		if candidate.Attempt != nil {
			attempt = *candidate.Attempt
		}
		if selected == nil || candidate.Marker == "gh-aw-execution-v1" {
			selected = candidate
		}
	}
	if workflowID != "" && workflowID != dailyFileDietWorkflow {
		return nil, errFileDietReferenceNotFound
	}
	if selected == nil && workflowID != dailyFileDietWorkflow && trackerID != dailyFileDietWorkflow {
		return nil, errFileDietReferenceNotFound
	}
	if selected == nil {
		selected = &fileDietReference{Repository: dailyFileDietRepository, Marker: "tracking-only"}
	}
	selected.WorkflowID = dailyFileDietWorkflow
	if trackerID != "" {
		selected.TrackerID = &trackerID
	}
	return selected, nil
}

type fileDietGraphEntity struct {
	Type       string `json:"__typename"`
	ID         string `json:"id"`
	Number     int    `json:"number"`
	URL        string `json:"url"`
	Repository struct {
		Name string `json:"nameWithOwner"`
	} `json:"repository"`
	State       string  `json:"state"`
	StateReason *string `json:"stateReason"`
	CreatedAt   string  `json:"createdAt"`
	UpdatedAt   string  `json:"updatedAt"`
	ClosedAt    *string `json:"closedAt"`
	MergedAt    *string `json:"mergedAt"`
	HeadRefOID  string  `json:"headRefOid"`
	MergeCommit *struct {
		OID string `json:"oid"`
	} `json:"mergeCommit"`
	ClosingIssuesReferences *struct {
		Nodes    []fileDietGraphEntity `json:"nodes"`
		PageInfo struct {
			HasNextPage bool `json:"hasNextPage"`
		} `json:"pageInfo"`
	} `json:"closingIssuesReferences"`
	TimelineItems *struct {
		Nodes []struct {
			Type      string               `json:"__typename"`
			CreatedAt string               `json:"createdAt"`
			Closer    *fileDietGraphEntity `json:"closer"`
			Source    *fileDietGraphEntity `json:"source"`
		} `json:"nodes"`
		PageInfo struct {
			HasNextPage bool `json:"hasNextPage"`
		} `json:"pageInfo"`
	} `json:"timelineItems"`
}

func fileDietGraphTarget(entity fileDietGraphEntity) (fileDietTarget, error) {
	target := fileDietTarget{entity.ID, entity.Number, entity.Repository.Name, entity.URL}
	if target.ID == "" || target.Number <= 0 || target.Repository == "" ||
		target.URL != "https://github.com/"+target.Repository+"/issues/"+strconv.Itoa(target.Number) &&
			target.URL != "https://github.com/"+target.Repository+"/pull/"+strconv.Itoa(target.Number) {
		return target, errors.New("invalid File Diet graph entity identity")
	}
	return target, nil
}

func fileDietNormalizeGraph(entity fileDietGraphEntity, observed string) (fileDietGraph, error) {
	var graph fileDietGraph
	ref, err := fileDietGraphTarget(entity)
	if err != nil {
		return graph, err
	}
	if !strings.EqualFold(ref.Repository, dailyFileDietRepository) ||
		(entity.Type != "Issue" && entity.Type != "PullRequest") ||
		!fileDietInstant(observed) || !fileDietInstant(entity.CreatedAt) || !fileDietInstant(entity.UpdatedAt) ||
		entity.TimelineItems == nil || entity.TimelineItems.Nodes == nil {
		return graph, errors.New("incomplete File Diet entity graph")
	}
	for _, optional := range []*string{entity.ClosedAt, entity.MergedAt} {
		if optional != nil && !fileDietInstant(*optional) {
			return graph, errors.New("invalid File Diet graph timestamp")
		}
	}
	graph = fileDietGraph{
		fileDietTarget: ref, Kind: entity.Type, State: entity.State, StateReason: entity.StateReason,
		CreatedAt: entity.CreatedAt, UpdatedAt: entity.UpdatedAt, ClosedAt: entity.ClosedAt,
		MergedAt: entity.MergedAt, ObservedAt: observed,
		HistoryComplete:      !entity.TimelineItems.PageInfo.HasNextPage,
		ClosingLinksComplete: true, Edges: []fileDietEdge{}, Events: []fileDietGraphEvent{},
	}
	if entity.MergeCommit != nil {
		graph.MergeCommit = &entity.MergeCommit.OID
	}
	for _, event := range entity.TimelineItems.Nodes {
		if !fileDietInstant(event.CreatedAt) {
			return fileDietGraph{}, errors.New("file Diet graph event lacks timestamp")
		}
		kind := map[string]string{
			"ClosedEvent": "closed", "ReopenedEvent": "reopened",
			"MergedEvent": "merged", "CrossReferencedEvent": "referenced",
		}[event.Type]
		if kind == "" {
			return fileDietGraph{}, errors.New("unexpected File Diet graph event")
		}
		projected := fileDietGraphEvent{Type: kind, At: event.CreatedAt}
		if kind == "closed" && event.Closer != nil && event.Closer.Type == "PullRequest" {
			target, err := fileDietGraphTarget(*event.Closer)
			if err != nil {
				return fileDietGraph{}, err
			}
			graph.Edges = append(graph.Edges, fileDietEdge{Relation: "closed-by", At: event.CreatedAt, Target: target})
			projected.CloserID = target.ID
		}
		if kind == "referenced" {
			if event.Source == nil {
				return fileDietGraph{}, errors.New("missing File Diet graph reference source")
			}
			target, err := fileDietGraphTarget(*event.Source)
			if err != nil {
				return fileDietGraph{}, err
			}
			graph.Edges = append(graph.Edges, fileDietEdge{Relation: "referenced-by", At: event.CreatedAt, Target: target})
		}
		graph.Events = append(graph.Events, projected)
	}
	if entity.Type == "PullRequest" {
		if entity.ClosingIssuesReferences == nil || entity.ClosingIssuesReferences.Nodes == nil {
			return fileDietGraph{}, errors.New("missing File Diet closing relationship coverage")
		}
		for _, issue := range entity.ClosingIssuesReferences.Nodes {
			target, err := fileDietGraphTarget(issue)
			if err != nil {
				return fileDietGraph{}, err
			}
			graph.Edges = append(graph.Edges, fileDietEdge{Relation: "declares-closing", Target: target})
		}
		graph.ClosingLinksComplete = !entity.ClosingIssuesReferences.PageInfo.HasNextPage
	}
	return graph, nil
}

func fileDietGraphs(ctx context.Context, read fileDietRead, numbers []int) (map[int]fileDietGraph, error) {
	graphs := make(map[int]fileDietGraph, len(numbers))
	for offset := 0; offset < len(numbers); offset += 10 {
		batch := numbers[offset:min(offset+10, len(numbers))]
		var response struct {
			Data struct {
				Repository map[string]fileDietGraphEntity `json:"repository"`
			} `json:"data"`
			Errors []json.RawMessage `json:"errors"`
		}
		var err error
		response, err = fileDietReadJSON[struct {
			Data struct {
				Repository map[string]fileDietGraphEntity `json:"repository"`
			} `json:"data"`
			Errors []json.RawMessage `json:"errors"`
		}](ctx, read, "graphql", remoteValueExpectedGraphQuery(dailyFileDietRepository, batch))
		if err != nil || len(response.Errors) > 0 || response.Data.Repository == nil {
			return nil, errors.New("incomplete File Diet graph acquisition")
		}
		for _, number := range batch {
			entity, ok := response.Data.Repository["n"+strconv.Itoa(number)]
			if !ok {
				return nil, errors.New("missing File Diet graph entity")
			}
			graph, err := fileDietNormalizeGraph(entity, time.Now().UTC().Truncate(time.Millisecond).Format("2006-01-02T15:04:05.000Z"))
			if err != nil || graph.Number != number {
				return nil, errors.New("file Diet graph identity changed")
			}
			graphs[number] = graph
		}
	}
	return graphs, nil
}

func fileDietReadTimeline(ctx context.Context, read fileDietRead, number int, until string) (fileDietTimeline, error) {
	result := fileDietTimeline{Events: []fileDietTimelineEvent{}}
	types := map[string]bool{"assigned": true, "unassigned": true, "connected": true,
		"disconnected": true, "cross-referenced": true, "closed": true, "reopened": true,
		"copilot_work_started": true, "copilot_work_finished": true, "merged": true}
	for page := 1; page <= 5; page++ {
		endpoint := fmt.Sprintf("repos/%s/issues/%d/timeline?per_page=100&page=%d", dailyFileDietRepository, number, page)
		var rows []struct {
			Event     string `json:"event"`
			CreatedAt string `json:"created_at"`
			Subject   *struct {
				Number        int             `json:"number"`
				Title         string          `json:"title"`
				Type          string          `json:"type"`
				PullRequest   json.RawMessage `json:"pull_request"`
				RepositoryURL string          `json:"repository_url"`
				Repository    *struct {
					FullName string `json:"full_name"`
				} `json:"repository"`
			} `json:"subject"`
			Source *struct {
				Issue *struct {
					Number        int             `json:"number"`
					Title         string          `json:"title"`
					Type          string          `json:"type"`
					PullRequest   json.RawMessage `json:"pull_request"`
					RepositoryURL string          `json:"repository_url"`
					Repository    *struct {
						FullName string `json:"full_name"`
					} `json:"repository"`
				} `json:"issue"`
			} `json:"source"`
		}
		var err error
		rows, err = fileDietReadJSON[[]struct {
			Event     string `json:"event"`
			CreatedAt string `json:"created_at"`
			Subject   *struct {
				Number        int             `json:"number"`
				Title         string          `json:"title"`
				Type          string          `json:"type"`
				PullRequest   json.RawMessage `json:"pull_request"`
				RepositoryURL string          `json:"repository_url"`
				Repository    *struct {
					FullName string `json:"full_name"`
				} `json:"repository"`
			} `json:"subject"`
			Source *struct {
				Issue *struct {
					Number        int             `json:"number"`
					Title         string          `json:"title"`
					Type          string          `json:"type"`
					PullRequest   json.RawMessage `json:"pull_request"`
					RepositoryURL string          `json:"repository_url"`
					Repository    *struct {
						FullName string `json:"full_name"`
					} `json:"repository"`
				} `json:"issue"`
			} `json:"source"`
		}](ctx, read, endpoint, "")
		if err != nil {
			return result, err
		}
		for _, row := range rows {
			if !types[row.Event] {
				continue
			}
			if !fileDietInstant(row.CreatedAt) {
				return result, errors.New("file Diet timeline event lacks a timestamp")
			}
			if !fileDietTime(row.CreatedAt).Before(fileDietTime(until)) {
				continue
			}
			event := fileDietTimelineEvent{Type: row.Event, At: row.CreatedAt}
			// Decode the two alternative subject shapes through the same bounded
			// projection, keeping foreign repositories out of related PR scope.
			var subject json.RawMessage
			if row.Subject != nil {
				subject, _ = json.Marshal(row.Subject)
			} else if row.Source != nil && row.Source.Issue != nil {
				subject, _ = json.Marshal(row.Source.Issue)
			}
			if len(subject) > 0 {
				var candidate struct {
					Number        int             `json:"number"`
					Title         string          `json:"title"`
					Type          string          `json:"type"`
					PullRequest   json.RawMessage `json:"pull_request"`
					RepositoryURL string          `json:"repository_url"`
					Repository    *struct {
						FullName string `json:"full_name"`
					} `json:"repository"`
				}
				_ = json.Unmarshal(subject, &candidate)
				repository := strings.TrimPrefix(candidate.RepositoryURL, "https://api.github.com/repos/")
				if candidate.Repository != nil && candidate.Repository.FullName != "" {
					repository = candidate.Repository.FullName
				}
				if strings.EqualFold(repository, dailyFileDietRepository) {
					if candidate.Number <= 0 {
						return result, errors.New("invalid File Diet timeline target")
					}
					kind := "issue"
					if candidate.Type == "pull_request" || len(candidate.PullRequest) > 0 &&
						!bytes.Equal(candidate.PullRequest, []byte("null")) {
						kind = "pull-request"
					}
					event.Target = &fileDietTimelineTarget{candidate.Number, candidate.Title, kind}
				}
			}
			result.Events = append(result.Events, event)
		}
		if len(rows) < 100 {
			result.Complete = true
			break
		}
	}
	return result, nil
}

type fileDietCommit struct {
	SHA    string `json:"sha"`
	Commit struct {
		Committer struct {
			Date string `json:"date"`
		} `json:"committer"`
	} `json:"commit"`
}

func fileDietAcquireHistory(ctx context.Context, read fileDietRead, until string, previous *fileDietProof) (fileDietProof, error) {
	var proof fileDietProof
	cutoff := fileDietTime(until)
	if cutoff.IsZero() || cutoff.After(time.Now()) || cutoff.Format(time.RFC3339) != until {
		return proof, errors.New("file Diet requires a valid non-future UTC cutoff")
	}
	if previous != nil && (!fileDietInstant(previous.Until) || fileDietTime(previous.Until).After(cutoff)) {
		return proof, errors.New("previous File Diet proof follows requested cutoff")
	}
	var identity struct {
		ID       int64  `json:"id"`
		FullName string `json:"full_name"`
	}
	for _, name := range []string{dailyFileDietRepository, "githubnext/gh-aw"} {
		got, err := fileDietReadJSON[struct {
			ID       int64  `json:"id"`
			FullName string `json:"full_name"`
		}](ctx, read, "repos/"+name, "")
		if err != nil || got.ID <= 0 || got.FullName != dailyFileDietRepository ||
			identity.ID != 0 && identity.ID != got.ID {
			return proof, errors.New("file Diet repository alias does not identify declared target")
		}
		identity = got
	}
	proof = fileDietProof{SchemaVersion: 1, Repository: dailyFileDietRepository,
		RepositoryID: identity.ID, Aliases: []string{dailyFileDietRepository, "githubnext/gh-aw"},
		SourcePath: fileDietSourcePath, Until: until,
		ObservedAt: time.Now().UTC().Truncate(time.Millisecond).Format("2006-01-02T15:04:05.000Z"),
		Discovery:  []fileDietDiscovery{}, Issues: []fileDietIssue{}, Pulls: []fileDietPull{},
		Snapshots: []fileDietSnapshot{}, History: []fileDietHistoryRevision{}}
	source := "repos/" + dailyFileDietRepository + "/commits?path=" + fileDietSourcePath
	if previous != nil {
		source += "&since=" + previous.Until
	}
	source += "&until=" + until + "&per_page=100"
	commits, err := fileDietReadJSON[[]fileDietCommit](ctx, read, source, "")
	if err != nil || len(commits) >= 100 || previous == nil && len(commits) == 0 {
		return proof, errors.New("file Diet workflow source history is absent or truncated")
	}
	if previous != nil {
		proof.Adoption = previous.Adoption
		revisions := map[string]fileDietHistoryRevision{}
		for _, row := range previous.History {
			revisions[row.Commit] = row
		}
		for _, row := range commits {
			revision := fileDietHistoryRevision{row.SHA, row.Commit.Committer.Date}
			if retained, ok := revisions[revision.Commit]; ok && retained != revision {
				return proof, errors.New("preserved File Diet source revision changed")
			}
			revisions[revision.Commit] = revision
		}
		for _, row := range revisions {
			proof.History = append(proof.History, row)
		}
		sort.Slice(proof.History, func(i, j int) bool {
			return fileDietTime(proof.History[i].At).After(fileDietTime(proof.History[j].At))
		})
	} else {
		oldest := commits[len(commits)-1]
		var introduction struct {
			Files   []struct{ Filename, Status string } `json:"files"`
			Parents []struct {
				SHA string `json:"sha"`
			} `json:"parents"`
		}
		introduction, err = fileDietReadJSON[struct {
			Files   []struct{ Filename, Status string } `json:"files"`
			Parents []struct {
				SHA string `json:"sha"`
			} `json:"parents"`
		}](ctx, read, "repos/"+dailyFileDietRepository+"/commits/"+oldest.SHA, "")
		if err != nil || len(introduction.Parents) != 1 {
			return proof, errors.New("file Diet workflow adoption identity is incomplete")
		}
		added := map[string]bool{}
		for _, file := range introduction.Files {
			if file.Status == "added" {
				added[file.Filename] = true
			}
		}
		if !added[fileDietSourcePath] || !added[strings.TrimSuffix(fileDietSourcePath, ".md")+".lock.yml"] {
			return proof, errors.New("file Diet workflow adoption identity is incomplete")
		}
		proof.Adoption = fileDietAdoption{Commit: oldest.SHA,
			At: oldest.Commit.Committer.Date, BaselineCommit: introduction.Parents[0].SHA}
		for _, row := range commits {
			proof.History = append(proof.History, fileDietHistoryRevision{row.SHA, row.Commit.Committer.Date})
		}
	}
	if proof.Adoption.Commit != "1186030a620f4113f655c156bedf70cf2c164f79" ||
		proof.Adoption.At != "2025-11-15T13:36:21Z" {
		return proof, errors.New("file Diet frozen adoption changed")
	}
	discoveryStart := proof.Adoption.At
	field := "created"
	if previous != nil {
		discoveryStart, field = previous.Until, "updated"
	}
	terms := []string{`"[file-diet]" in:title`, `"gh-aw-workflow-id: daily-file-diet" in:body`,
		`"gh-aw-tracker-id: daily-file-diet" in:body`, `"gh-aw-agentic-workflow: Daily File Diet" in:body`,
		`"Daily File Diet" "AI generated by" in:body`, `"gh-aw-execution:" "daily-file-diet" in:body`}
	type searchItem struct {
		Number      int             `json:"number"`
		NodeID      string          `json:"node_id"`
		Title       string          `json:"title"`
		Body        string          `json:"body"`
		CreatedAt   string          `json:"created_at"`
		UpdatedAt   string          `json:"updated_at"`
		PullRequest json.RawMessage `json:"pull_request"`
	}
	found := map[int]searchItem{}
	for _, term := range terms {
		query := "repo:" + dailyFileDietRepository + " " + term + " " + field + ":" +
			discoveryStart[:10] + ".." + until[:10]
		total, count := -1, 0
		for page := 1; page <= 10; page++ {
			endpoint := fmt.Sprintf("search/issues?q=%s&sort=%s&order=asc&per_page=100&page=%d",
				url.QueryEscape(query), field, page)
			var batch struct {
				TotalCount        int          `json:"total_count"`
				IncompleteResults bool         `json:"incomplete_results"`
				Items             []searchItem `json:"items"`
			}
			batch, err = fileDietReadJSON[struct {
				TotalCount        int          `json:"total_count"`
				IncompleteResults bool         `json:"incomplete_results"`
				Items             []searchItem `json:"items"`
			}](ctx, read, endpoint, "")
			if err != nil || batch.IncompleteResults || batch.TotalCount >= 1000 || batch.Items == nil ||
				total >= 0 && total != batch.TotalCount {
				return proof, errors.New("file Diet issue search coverage is incomplete")
			}
			total = batch.TotalCount
			count += len(batch.Items)
			for _, item := range batch.Items {
				at := item.CreatedAt
				if field == "updated" {
					at = item.UpdatedAt
				}
				if !fileDietTime(at).Before(fileDietTime(discoveryStart)) && fileDietTime(at).Before(cutoff) {
					if retained, ok := found[item.Number]; ok && retained.NodeID != item.NodeID {
						return proof, errors.New("conflicting File Diet discovered output")
					}
					found[item.Number] = item
				}
			}
			if len(batch.Items) < 100 {
				break
			}
		}
		if count != total {
			return proof, errors.New("file Diet issue search coverage was truncated")
		}
		proof.Discovery = append(proof.Discovery, fileDietDiscovery{query, total, true})
	}
	previousIssues := map[int]fileDietIssue{}
	if previous != nil {
		for _, item := range previous.Issues {
			previousIssues[item.Number] = item
		}
	}
	newlySelected := map[int]searchItem{}
	issueNumbers := map[int]bool{}
	for number := range previousIssues {
		issueNumbers[number] = true
	}
	for _, item := range found {
		if len(item.PullRequest) != 0 && !bytes.Equal(item.PullRequest, []byte("null")) {
			continue
		}
		ref, err := fileDietReferenceFor(item.Body)
		if errors.Is(err, errFileDietReferenceNotFound) {
			continue
		}
		if err != nil {
			return proof, err
		}
		if ref != nil {
			newlySelected[item.Number], issueNumbers[item.Number] = item, true
		}
	}
	if len(issueNumbers) == 0 || len(issueNumbers) > 200 {
		return proof, errors.New("file Diet tracked output collection budget exceeded or no outputs found")
	}
	numbers := make([]int, 0, len(issueNumbers))
	for number := range issueNumbers {
		numbers = append(numbers, number)
	}
	slices.Sort(numbers)
	graphs, err := fileDietGraphs(ctx, read, numbers)
	if err != nil {
		return proof, err
	}
	for _, number := range numbers {
		timeline, err := fileDietReadTimeline(ctx, read, number, until)
		if err != nil {
			return proof, err
		}
		if retained, exists := previousIssues[number]; exists {
			retained.Graph, retained.Timeline = graphs[number], timeline
			proof.Issues = append(proof.Issues, retained)
			continue
		}
		item := newlySelected[number]
		ref, err := fileDietReferenceFor(item.Body)
		if err != nil || ref == nil {
			return proof, errors.New("file Diet output tracking changed")
		}
		run := fileDietRun{Unavailable: json.RawMessage("null")}
		var artifacts json.RawMessage = []byte("null")
		if ref.RunID == nil {
			run.Unavailable = []byte(`{"reason":"Tracking identity has no producer run reference"}`)
		} else {
			endpoint := "repos/" + dailyFileDietRepository + "/actions/runs/" + *ref.RunID
			var producer struct {
				ID         int64 `json:"id"`
				Repository struct {
					FullName string `json:"full_name"`
				} `json:"repository"`
				Path        string          `json:"path"`
				HeadSHA     string          `json:"head_sha"`
				RunAttempt  int             `json:"run_attempt"`
				CreatedAt   string          `json:"created_at"`
				HTMLURL     string          `json:"html_url"`
				Unavailable json.RawMessage `json:"unavailable"`
			}
			producer, err = fileDietReadJSON[struct {
				ID         int64 `json:"id"`
				Repository struct {
					FullName string `json:"full_name"`
				} `json:"repository"`
				Path        string          `json:"path"`
				HeadSHA     string          `json:"head_sha"`
				RunAttempt  int             `json:"run_attempt"`
				CreatedAt   string          `json:"created_at"`
				HTMLURL     string          `json:"html_url"`
				Unavailable json.RawMessage `json:"unavailable"`
			}](ctx, read, endpoint, "")
			if err != nil {
				return proof, err
			}
			if len(producer.Unavailable) != 0 {
				run.Unavailable = producer.Unavailable
			} else {
				if strconv.FormatInt(producer.ID, 10) != *ref.RunID ||
					!strings.EqualFold(producer.Repository.FullName, dailyFileDietRepository) &&
						!strings.EqualFold(producer.Repository.FullName, "githubnext/gh-aw") ||
					strings.Split(producer.Path, "@")[0] != ".github/workflows/daily-file-diet.lock.yml" ||
					!validFileDietSHA(producer.HeadSHA) ||
					ref.Attempt != nil && producer.RunAttempt != *ref.Attempt {
					return proof, errors.New("file Diet producer run does not match workflow, repository, revision or attempt")
				}
				run.Validation = &fileDietValidation{"verified-run-reference", producer.HeadSHA,
					producer.RunAttempt, fileDietSourcePath, producer.CreatedAt, producer.HTMLURL,
					"Tracking and run references are not applied safe-output receipts."}
				var inventory struct {
					TotalCount int               `json:"total_count"`
					Artifacts  []json.RawMessage `json:"artifacts"`
				}
				inventory, err = fileDietReadJSON[struct {
					TotalCount int               `json:"total_count"`
					Artifacts  []json.RawMessage `json:"artifacts"`
				}](ctx, read, endpoint+"/artifacts?per_page=100", "")
				if err != nil || inventory.Artifacts == nil || inventory.TotalCount != len(inventory.Artifacts) {
					return proof, errors.New("truncated File Diet producer artifact inventory")
				}
				artifacts, _ = json.Marshal(inventory.Artifacts)
			}
		}
		target := fileDietPathPattern.FindString(item.Title)
		if target == "" {
			target = fileDietPathPattern.FindString(item.Body)
		}
		var path *string
		if target != "" {
			path = &target
		}
		proof.Issues = append(proof.Issues, fileDietIssue{
			Number: number, ID: item.NodeID, Title: item.Title, CreatedAt: item.CreatedAt,
			Eligible: func() *bool {
				ok := fileDietSourceName.MatchString(item.Title) ||
					fileDietRefactor.MatchString(item.Title) && fileDietPathPattern.MatchString(item.Body)
				return &ok
			}(),
			BodySHA256: fileDietRawBytesDigest([]byte(item.Body)), TargetPath: path,
			Reference: *ref, Run: run, RetainedArtifacts: artifacts, Graph: graphs[number],
			Timeline: timeline,
		})
	}
	related := map[int]bool{}
	if previous != nil {
		for _, pull := range previous.Pulls {
			related[pull.Number] = true
		}
	}
	for _, item := range found {
		if len(item.PullRequest) == 0 || bytes.Equal(item.PullRequest, []byte("null")) {
			continue
		}
		ref, err := fileDietReferenceFor(item.Body)
		if errors.Is(err, errFileDietReferenceNotFound) {
			continue
		}
		if err != nil {
			return proof, err
		}
		if fileDietSourceName.MatchString(item.Title) || ref != nil {
			related[item.Number] = true
		}
	}
	for _, issue := range proof.Issues {
		for _, event := range issue.Timeline.Events {
			if event.Target != nil && event.Target.Kind == "pull-request" {
				related[event.Target.Number] = true
			}
		}
		for _, edge := range issue.Graph.Edges {
			if edge.Target.Repository == dailyFileDietRepository &&
				edge.Target.URL == fmt.Sprintf("https://github.com/%s/pull/%d",
					dailyFileDietRepository, edge.Target.Number) {
				related[edge.Target.Number] = true
			}
		}
	}
	if len(related) > 100 {
		return proof, errors.New("related File Diet implementation budget exceeded")
	}
	pullNumbers := make([]int, 0, len(related))
	for number := range related {
		pullNumbers = append(pullNumbers, number)
	}
	slices.Sort(pullNumbers)
	previousPulls := map[int]fileDietPull{}
	if previous != nil {
		for _, pull := range previous.Pulls {
			previousPulls[pull.Number] = pull
		}
	}
	for _, number := range pullNumbers {
		if retained, ok := previousPulls[number]; ok && retained.MergedAt != nil &&
			fileDietTime(*retained.MergedAt).Before(fileDietTime(previous.Until)) {
			proof.Pulls = append(proof.Pulls, retained)
			continue
		}
		endpoint := fmt.Sprintf("repos/%s/pulls/%d", dailyFileDietRepository, number)
		var pull struct {
			Number    int     `json:"number"`
			NodeID    string  `json:"node_id"`
			Title     string  `json:"title"`
			CreatedAt string  `json:"created_at"`
			MergedAt  *string `json:"merged_at"`
			Head      struct {
				SHA string `json:"sha"`
			} `json:"head"`
			Base struct {
				SHA string `json:"sha"`
			} `json:"base"`
			MergeCommitSHA string `json:"merge_commit_sha"`
			ChangedFiles   int    `json:"changed_files"`
		}
		pull, err = fileDietReadJSON[struct {
			Number    int     `json:"number"`
			NodeID    string  `json:"node_id"`
			Title     string  `json:"title"`
			CreatedAt string  `json:"created_at"`
			MergedAt  *string `json:"merged_at"`
			Head      struct {
				SHA string `json:"sha"`
			} `json:"head"`
			Base struct {
				SHA string `json:"sha"`
			} `json:"base"`
			MergeCommitSHA string `json:"merge_commit_sha"`
			ChangedFiles   int    `json:"changed_files"`
		}](ctx, read, endpoint, "")
		if err != nil || pull.Number != number || pull.NodeID == "" || pull.ChangedFiles > 1000 {
			return proof, errors.New("invalid File Diet implementation metadata")
		}
		graph, err := fileDietGraphs(ctx, read, []int{number})
		if err != nil {
			return proof, err
		}
		files := []fileDietPullFile{}
		for page := 1; page <= 10; page++ {
			var pageFiles []struct {
				Filename         string  `json:"filename"`
				Status           string  `json:"status"`
				PreviousFilename *string `json:"previous_filename"`
			}
			pageFiles, err = fileDietReadJSON[[]struct {
				Filename         string  `json:"filename"`
				Status           string  `json:"status"`
				PreviousFilename *string `json:"previous_filename"`
			}](ctx, read, fmt.Sprintf("%s/files?per_page=100&page=%d", endpoint, page), "")
			if err != nil || pageFiles == nil {
				return proof, errors.New("invalid File Diet implementation file inventory")
			}
			for _, file := range pageFiles {
				files = append(files, fileDietPullFile{file.Filename, file.Status, file.PreviousFilename})
			}
			if len(pageFiles) < 100 {
				break
			}
		}
		if len(files) != pull.ChangedFiles {
			return proof, errors.New("truncated File Diet implementation file inventory")
		}
		var mergeSHA *string
		if pull.MergedAt != nil {
			mergeSHA = &pull.MergeCommitSHA
		}
		proof.Pulls = append(proof.Pulls, fileDietPull{
			Number: number, ID: pull.NodeID, Title: pull.Title, CreatedAt: pull.CreatedAt,
			MergedAt: pull.MergedAt, HeadSHA: pull.Head.SHA, BaseSHA: pull.Base.SHA,
			MergeSHA: mergeSHA, Graph: graph[number], Files: files,
		})
	}
	start := fileDietTime(proof.Adoption.At)
	if previous != nil {
		start = fileDietTime(previous.Until)
	}
	if previous == nil {
		proof.Snapshots = append(proof.Snapshots, fileDietSnapshot{proof.Adoption.At, proof.Adoption.Commit})
		start = time.Date(start.Year(), start.Month()+1, 1, 0, 0, 0, 0, time.UTC)
	} else {
		start = time.Date(start.Year(), start.Month(), start.Day()+1, 0, 0, 0, 0, time.UTC)
	}
	cutoffs := []time.Time{}
	for start.Before(cutoff) && len(cutoffs) < 4096 {
		cutoffs = append(cutoffs, start)
		if previous == nil {
			start = start.AddDate(0, 1, 0)
		} else {
			start = start.AddDate(0, 0, 1)
		}
	}
	if len(cutoffs) == 4096 {
		return proof, errors.New("file Diet snapshot cadence exceeds bounded collection")
	}
	cutoffs = append(cutoffs, cutoff)
	for _, at := range cutoffs {
		instant := at.UTC().Format(time.RFC3339)
		before := at.Add(-time.Second).UTC().Format("2006-01-02T15:04:05.000Z")
		commits, err := fileDietReadJSON[[]fileDietCommit](ctx, read,
			"repos/"+dailyFileDietRepository+"/commits?until="+before+"&per_page=1", "")
		if err != nil || len(commits) != 1 ||
			!fileDietTime(commits[0].Commit.Committer.Date).Before(at) {
			return proof, errors.New("missing immutable File Diet snapshot cutoff")
		}
		proof.Snapshots = append(proof.Snapshots, fileDietSnapshot{instant, commits[0].SHA})
	}
	if previous != nil {
		snapshots := map[string]fileDietSnapshot{}
		for _, row := range previous.Snapshots {
			snapshots[row.At] = row
		}
		for _, row := range proof.Snapshots {
			if retained, ok := snapshots[row.At]; ok && retained != row {
				return proof, errors.New("preserved File Diet snapshot revision changed")
			}
			snapshots[row.At] = row
		}
		proof.Snapshots = proof.Snapshots[:0]
		for _, row := range snapshots {
			proof.Snapshots = append(proof.Snapshots, row)
		}
		sort.Slice(proof.Snapshots, func(i, j int) bool {
			return proof.Snapshots[i].At < proof.Snapshots[j].At
		})
	}
	return proof, nil
}
